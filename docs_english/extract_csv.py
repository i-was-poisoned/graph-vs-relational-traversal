"""Extract the benchmark's actor/repo graph from a GH Archive file into CSV files.

Reads the JSON Lines file once, skips bot accounts (logins ending in "[bot]"),
and writes three CSV files that both databases are loaded from, so they always
hold exactly the same data:

    actors.csv       id, login             one row per actor (most recent login)
    repos.csv        id, name              one row per repo (most recent name)
    actor_repo.csv   actor_id, repo_id     one row per actor-repo pair, no repeats

Usage:
    python scripts/extract_csv.py
    python scripts/extract_csv.py --file data/2026-08-27-15.json --out-dir data/csv
"""

# ---------------------------------------------------------------------
# import csv
#
# NEW: the standard-library module for reading and writing CSV files
# ("comma-separated values"): plain-text tables where each line is a row
# and commas separate the columns, e.g.
#
#     id,login
#     19,brynary
#
# Why not just write the commas ourselves with f"{a},{b}"? Because if a
# value ever contained a comma or a quote, the table would break. The csv
# module handles those cases (it adds quotes where needed), and both
# PostgreSQL and Neo4j read its output without trouble.
#
# argparse, json, Path: already explained in the earlier annotated scripts.
# ---------------------------------------------------------------------
import argparse
import csv
import json
from pathlib import Path

# ---------------------------------------------------------------------
# PROJECT_DIR = Path(__file__).resolve().parent.parent
#
# The same technique as DEFAULT_FILE in the earlier scripts (see
# peek_data.py's annotated copy), saved in its own constant because two
# defaults are built from it:
#   DEFAULT_FILE     data/2026-08-27-15.json   the input
#   DEFAULT_OUT_DIR  data/csv/                 where the CSVs go
#
# The CSVs go inside data/ on purpose: data/ is already in .gitignore,
# because everything in it can be regenerated by running the scripts again.
# ---------------------------------------------------------------------
PROJECT_DIR = Path(__file__).resolve().parent.parent
DEFAULT_FILE = PROJECT_DIR / "data" / "2026-08-27-15.json"
DEFAULT_OUT_DIR = PROJECT_DIR / "data" / "csv"

# Same bot rule as summarize_data.py (see its annotated copy): official
# GitHub bots have logins ending in "[bot]". The benchmark excludes them
# because they act as artificial hubs between unrelated repos.
BOT_SUFFIX = "[bot]"


def is_bot(login: str) -> bool:
    return login.endswith(BOT_SUFFIX)


# ---------------------------------------------------------------------
# def remember_latest(names, key, created_at, name) -> None:
#
# WHY IT EXISTS: in this hour of data, one user changed their login
# (lucky521-png -> peitongshi) and two repos were renamed. Their id stays
# the same, but the name changes from one event to the next. Each id must
# appear only ONCE in the CSV, so we have to pick one name: the most
# recent one.
#
# HOW: `names` is a dict whose keys are ids and whose values are TUPLES
# of two things, (created_at, name):
#
#     names[321725054] = ("2026-08-27T15:35:35Z", "peitongshi")
#
# A tuple is like a small list that can't be changed, used here to keep
# two related values together. names[key][0] is the time, names[key][1]
# is the name.
#
# The `if` saves the new name when:
#   key not in names           it's the first time we see this id, or
#   created_at >= names[key][0] this event is as recent as, or more recent
#                              than, the one we had saved.
#
# Comparing TIMES AS TEXT: created_at is written in ISO 8601 format
# ("2026-08-27T15:35:35Z": year, month, day, hour, minute, second, from
# biggest to smallest, always with the same number of digits). In that
# format, alphabetical order IS time order, so `>=` on the strings works
# without converting them to dates.
#
# `-> None`: it doesn't return anything; it changes the dict it was given.
# Dicts are passed "by reference": the function works on the same dict
# the caller has, not on a copy.
# ---------------------------------------------------------------------
def remember_latest(names: dict[int, tuple[str, str]], key: int, created_at: str, name: str) -> None:
    # Keep the name from the most recent event: logins and repo names can change.
    # created_at is ISO 8601 text, so comparing the strings compares the times.
    if key not in names or created_at >= names[key][0]:
        names[key] = (created_at, name)


# ---------------------------------------------------------------------
# def extract(file_path) -> tuple[...]:
#
# Reads the file once and returns FOUR things at the same time. The type
# hint looks like a tongue-twister, but it's only two small kinds of
# TUPLE plus one big one. Let's go from the inside out, with real data.
#
# 1. WHAT A TUPLE IS
#    A fixed group of values that belong together, in brackets. Think of
#    a CARD WITH BOXES: the number of boxes never changes, and each box
#    means something by its POSITION. [0] reads the first box, [1] the
#    second:
#
#        card = ("2026-08-27T15:35:35Z", "peitongshi")
#        card[0]   # "2026-08-27T15:35:35Z"  <- the time
#        card[1]   # "peitongshi"            <- the name
#
#    Like a list, but it can NEVER be changed once created.
#
# 2. THE TWO SMALL CARDS
#    (time, name)          used in actors and repos
#    (actor_id, repo_id)   used in pairs = ONE connection
#
# 3. WHERE THEY GO
#    actors: a dict whose VALUES are (time, name) cards
#        actors = {321725054: ("2026-08-27T15:35:35Z", "peitongshi"),
#                  19:        ("2026-08-27T15:02:11Z", "brynary"), ...}
#        -> dict[int, tuple[str, str]]  "number -> card of two texts"
#    repos: exactly the same, for repos.
#    pairs: a SET of (actor_id, repo_id) cards
#        pairs = {(321725054, 1348625135), (19, 1310070394), ...}
#        -> set[tuple[int, int]]  "set of cards of two numbers"
#
# 4. THE BIG CARD: WHAT extract() RETURNS
#    A function can only return ONE thing. To return four, they're put in
#    a card with FOUR boxes:
#
#        return actors, repos, pairs, skipped_bot_events
#
#    and main() opens it and spreads the four boxes into four variables:
#
#        actors, repos, pairs, skipped_bot_events = extract(args.file)
#
# THE WHOLE PICTURE
#
#    extract() returns ONE tuple with 4 boxes:
#    |-- box 1: actors   dict   321725054 -> ("2026-08-27T15:35:35Z", "peitongshi")
#    |                                        '---- small card: time, name ----'
#    |-- box 2: repos    dict   (same as actors, for repos)
#    |-- box 3: pairs    set    {(321725054, 1348625135), (19, 1310070394), ...}
#    |                            '-- small card: actor, repo = 1 connection --'
#    '-- box 4: skipped_bot_events   a number: 1970
#
# THE TYPE HINT, READ PIECE BY PIECE
#
#    -> tuple[                          a card with 4 boxes:
#        dict[int, tuple[str, str]],      1. actors: id -> (time, name)
#        dict[int, tuple[str, str]],      2. repos:  id -> (time, name)
#        set[tuple[int, int]],            3. pairs:  set of (actor_id, repo_id)
#        int,                             4. skipped_bot_events: a number
#    ]
# ---------------------------------------------------------------------
def extract(file_path: Path) -> tuple[dict[int, tuple[str, str]], dict[int, tuple[str, str]], set[tuple[int, int]], int]:
    actors: dict[int, tuple[str, str]] = {}
    repos: dict[int, tuple[str, str]] = {}

    # -----------------------------------------------------------------
    # pairs: set[tuple[int, int]] = set()
    #
    # THIS is how "one connection per actor-repo pair, no repeats" is
    # done. Each connection is a tuple (actor_id, repo_id), and a SET
    # keeps each item only once (see summarize_data.py's annotated copy).
    # If ana pushes 10 times to the same repo, pairs.add((ana_id, repo_id))
    # runs 10 times, but the set keeps just one copy. That's why 67,459
    # non-bot events become only 15,053 connections.
    #
    # (Tuples can go in a set; lists can't, because a set needs items that
    # can never change — and tuples can't be changed.)
    # -----------------------------------------------------------------
    pairs: set[tuple[int, int]] = set()
    skipped_bot_events = 0

    with open(file_path, "r", encoding="utf-8") as f:
        for line in f:
            event = json.loads(line)
            actor = event["actor"]
            repo = event["repo"]

            # Same skip-and-count pattern as before: `continue` jumps to the
            # next line without reaching the code below.
            if is_bot(actor["login"]):
                skipped_bot_events += 1
                continue

            # The ids (actor["id"], repo["id"]) are the keys everywhere —
            # never the names, which can change (see remember_latest).
            remember_latest(actors, actor["id"], event["created_at"], actor["login"])
            remember_latest(repos, repo["id"], event["created_at"], repo["name"])
            pairs.add((actor["id"], repo["id"]))

    return actors, repos, pairs, skipped_bot_events


# ---------------------------------------------------------------------
# def write_csv(path, header, rows) -> None:
#
# Writes one CSV file: a header line with the column names, then one line
# per row. Used three times, once per file.
#
# open(path, "w", encoding="utf-8", newline="")
#   "w"         WRITE mode: creates the file, or empties it if it exists.
#   newline=""  required by the csv module: it writes the line endings
#               itself, and without this, Windows would add an extra
#               blank line between rows.
#
# csv.writer(f)          an object that turns rows into CSV lines.
# writer.writerow(...)   writes ONE row (here, the header).
# writer.writerows(...)  writes MANY rows at once (all the data).
#
# rows: list[tuple]  each row is a tuple, e.g. (19, "brynary"), and each
# value in the tuple becomes one column.
#
# {path.name:<16}  path.name is just the file name ("actors.csv"), without
# the folders; :<16 pads it to 16 characters so the counts line up.
# ---------------------------------------------------------------------
def write_csv(path: Path, header: list[str], rows: list[tuple]) -> None:
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)
    print(f"  {path.name:<16} {len(rows):>7} rows")


# parse_args(): same pattern as the earlier scripts. --out-dir lets you
# choose a different output folder; type=Path converts it, as with --file.
def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--file", type=Path, default=DEFAULT_FILE,
                         help=f"Path to the JSON Lines file (default: {DEFAULT_FILE})")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR,
                         help=f"Folder to write the CSV files to (default: {DEFAULT_OUT_DIR})")
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    # extract() returns a tuple of four values; this line UNPACKS it into
    # four variables at once (same idea as `for key, value in ...`).
    actors, repos, pairs, skipped_bot_events = extract(args.file)

    # -----------------------------------------------------------------
    # args.out_dir.mkdir(parents=True, exist_ok=True)
    #
    # Creates the output folder (data/csv/) if it doesn't exist yet.
    #   parents=True   also creates any missing folders above it.
    #   exist_ok=True  don't fail if the folder already exists (e.g. on
    #                  the second run).
    # -----------------------------------------------------------------
    args.out_dir.mkdir(parents=True, exist_ok=True)
    print(f"Skipped {skipped_bot_events} bot events. Writing to {args.out_dir}:")

    # -----------------------------------------------------------------
    # Building the rows: sorted(...) + a list comprehension
    #
    # sorted(actors.items()) gives the (id, (created_at, login)) pairs
    # ORDERED BY ID. The comprehension then keeps only what goes in the
    # file:
    #     for actor_id, (_, login) in ...
    # unpacks each pair, and the inner tuple too: `_` is the created_at,
    # which we don't need any more ("a value I don't need", as in
    # check_connections.py). Each row becomes (actor_id, login).
    #
    # For actor_repo.csv, sorted(pairs) turns the set into a list of
    # tuples ordered by actor_id, then by repo_id.
    #
    # WHY SORT: a set and the order events arrive in don't give a fixed
    # order. Sorting means the same input ALWAYS produces exactly the same
    # files, byte for byte — so it's easy to check that a later run didn't
    # change anything. Reproducibility again.
    # -----------------------------------------------------------------
    # Sorted by id so the same input always produces byte-for-byte the same files.
    write_csv(args.out_dir / "actors.csv", ["id", "login"],
              [(actor_id, login) for actor_id, (_, login) in sorted(actors.items())])
    write_csv(args.out_dir / "repos.csv", ["id", "name"],
              [(repo_id, name) for repo_id, (_, name) in sorted(repos.items())])
    write_csv(args.out_dir / "actor_repo.csv", ["actor_id", "repo_id"], sorted(pairs))


# main() and the `if __name__ == "__main__":` guard: identical purpose and
# mechanics to the other scripts — see download_gharchive.py's annotated
# copy for the full explanation.
if __name__ == "__main__":
    main()
